export function isFullAppCommand(text: string): boolean {
  if (!text) return false
  const t = text.toLowerCase()
  return (
    t.includes("full app") ||
    t.includes("full test") ||
    t.includes("entire app") ||
    t.includes("test everything") ||
    t.includes("map and test") ||
    t.includes("map app") ||
    t.includes("systematic test") ||
    t.includes("map first") ||
    t.includes("test plan first") ||
    t.includes("map the entire application") ||
    t.includes("figma-style") ||
    t.includes("map all screens") ||
    (t.includes("map") && t.includes("application")) ||
    (t.includes("map") && t.includes("screens"))
  )
}

export function normalizePath(urlStr: string, origin: string): string {
  try {
    const u = new URL(urlStr)
    return u.pathname || "/"
  } catch {
    return urlStr.replace(origin, "").split("?")[0] || "/"
  }
}

/**
 * Normalized key for step-target drift checks: origin + pathname + search.
 * The hash is intentionally excluded — the engine's #modal-* / #tab-* markers
 * are synthetic and never appear in the live browser URL, while query-param
 * states (e.g. /leases?tab=expired) must trigger restoration.
 */
export function normalizeUrlForRestore(urlStr: string): string {
  try {
    const u = new URL(urlStr)
    return `${u.origin}${u.pathname}${u.search}`
  } catch {
    return urlStr.split("#")[0]
  }
}

export function deriveScreenName(
  pathStr: string,
  heading?: string,
  modalTitle?: string,
  isLoginWall?: boolean
): string {
  if (modalTitle) return `${modalTitle} (Modal)`
  if (isLoginWall) return "Sign In / Login"
  if (heading && heading.length < 40 && !heading.toLowerCase().includes("welcome")) {
    return heading.trim()
  }
  const clean = pathStr.replace(/^\//, "").replace(/\/$/, "")
  if (!clean) return "Home / Dashboard"
  return clean
    .split("/")
    .map((seg) => seg.charAt(0).toUpperCase() + seg.slice(1).replace(/[-_]/g, " "))
    .join(" - ")
}

/**
 * Builds the Figma-style FlowGraph representation from the FullAppTestPlan
 */
export function buildFigmaWorkflowMap(plan: FullAppTestPlan): FlowGraph {
  const nodes = plan.screens.map((s) => ({
    id: s.id,
    title: `${s.id} ${s.name}`,
    url: s.url,
    screenshotUrl: s.screenshotUrl,
    componentLocation: s.componentLocation || s.sourceFile,
  }))

  const edges = plan.transitions.map((t) => ({
    from: t.fromScreenId,
    to: t.toScreenId,
    label: t.action,
  }))

  return { nodes, edges }
}

/**
 * Ensures every action / step in the plan is represented by its own distinct screen node
 * so the Figma-style Workflow Map renders a screen card for every single action.
 */
export function ensureEveryActionHasScreen(plan: FullAppTestPlan): FullAppTestPlan {
  if (!plan || !plan.steps || plan.steps.length === 0) return plan

  const existingScreensMap = new Map<string, AppScreenNode>()
  for (const s of plan.screens) {
    existingScreensMap.set(s.id, s)
  }

  const updatedScreens = [...plan.screens]
  const updatedTransitions = [...plan.transitions]
  const rootScreenId = plan.screens[0]?.id || "S001"

  plan.steps.forEach((step, idx) => {
    const assignedScreen = existingScreensMap.get(step.screenId)
    // If step is sharing the root screen with other steps or doesn't have its own screen
    const isSharedRoot = step.screenId === rootScreenId && idx > 0
    const needsDistinctScreen = isSharedRoot || !assignedScreen

    if (needsDistinctScreen) {
      const newScreenId = `S${String(updatedScreens.length + 1).padStart(3, "0")}`
      const actionName = step.targetName || `Action ${idx + 1}`
      const screenTitle = `${actionName} (${step.actionType || "Action"})`
      const screenShot = step.screenshotUrl || assignedScreen?.screenshotUrl || updatedScreens[0]?.screenshotUrl
      const compLoc = assignedScreen?.componentLocation || assignedScreen?.sourceFile

      const newScreenNode: AppScreenNode = {
        id: newScreenId,
        name: screenTitle,
        url: assignedScreen?.url || plan.targetUrl,
        path: assignedScreen?.path ? `${assignedScreen.path}#step-${step.stepIndex}` : `/#step-${step.stepIndex}`,
        componentLocation: compLoc,
        sourceFile: compLoc,
        screenshotUrl: screenShot,
        actionableElements: [
          {
            id: `${newScreenId}-elem-1`,
            name: actionName,
            type: step.actionType === "fill" ? "input" : "button",
            tested: step.status === "passed" || step.status === "failed",
            testStatus: step.status === "passed" ? "passed" : step.status === "failed" ? "failed" : "pending",
            isInteractive: true,
          },
        ],
        forms: [],
        discoveredAt: new Date().toISOString(),
      }

      updatedScreens.push(newScreenNode)
      existingScreensMap.set(newScreenId, newScreenNode)

      step.screenId = newScreenId
      step.screenName = screenTitle
      step.url = newScreenNode.url
      step.componentLocation = compLoc
      if (screenShot && !step.screenshotUrl) {
        step.screenshotUrl = screenShot
      }

      const fromId = idx === 0 ? rootScreenId : (plan.steps[idx - 1]?.screenId || rootScreenId)
      const isLogoutStep = /log\s*out|sign\s*out|log\s*off/i.test(actionName)

      updatedTransitions.push({
        id: `tr-step-${idx + 1}-${newScreenId}`,
        fromScreenId: fromId,
        toScreenId: newScreenId,
        action: `${step.actionType === "fill" ? "Enter" : "Click"} ${actionName}`,
        actionType: step.actionType === "fill" ? "form_submit" : "click",
      })

      if (isLogoutStep) {
        // Explicitly map Logout screen back to root Login node to close the workflow lifecycle loop!
        if (!updatedTransitions.some((t) => t.fromScreenId === newScreenId && t.toScreenId === rootScreenId)) {
          updatedTransitions.push({
            id: `tr-logout-to-login-${idx + 1}`,
            fromScreenId: newScreenId,
            toScreenId: rootScreenId,
            action: "Redirect to Login ➔ Workflow Completed",
            actionType: "navigation",
          })
        }
      } else {
        // Add verified backward return transition so map flow verifies bidirectional integrity
        updatedTransitions.push({
          id: `tr-return-${idx + 1}-${newScreenId}`,
          fromScreenId: newScreenId,
          toScreenId: fromId,
          action: `Return / Back ↩️ (Verified)`,
          actionType: /modal|dialog/i.test(screenTitle) ? "modal_close" : "navigation",
        })
      }
    }
  })

  plan.screens = updatedScreens
  plan.transitions = updatedTransitions
  return plan
}

/**
 * Synthesize a FullAppTestPlan from the DOM Discovery Graph.
 * Converts domDiscoveryGraph nodes/edges into proper screens and transitions.
 * Used by Full App Testing mode (human-test-loop).
 */
export function synthesizeFullAppPlanFromDomGraph(job: AutomationJob): FullAppTestPlan | null {
  if (!job.domDiscoveryGraph || !job.domDiscoveryGraph.nodes || job.domDiscoveryGraph.nodes.length === 0) {
    return null
  }

  const graph = job.domDiscoveryGraph
  
  // Convert DOM graph nodes to AppScreenNodes
  const screens: AppScreenNode[] = graph.nodes.map((node, index) => {
    // Extract elements from action ledger for this screen
    const screenElements = (job.actionLedger?.entries || [])
      .filter(entry => entry.screenUrl === node.url)
      .map((entry, idx) => ({
        id: `${node.id}-elem-${idx + 1}`,
        name: entry.name,
        type: entry.type,
        selector: entry.selector,
        href: entry.href,
        tested: entry.status !== 'untested',
        testStatus: entry.status === 'passed' ? 'passed' as const : 
                   entry.status === 'failed' ? 'failed' as const :
                   entry.status === 'blocked' ? 'blocked' as const : 'pending' as const,
        isInteractive: true,
      }))

    let path = '/'
    try {
      path = new URL(node.url).pathname || '/'
    } catch {}

    return {
      id: `S${String(index + 1).padStart(3, '0')}`,
      name: node.title || path,
      url: node.url,
      path,
      screenshotUrl: undefined, // Screenshots come from ledger or elsewhere
      actionableElements: screenElements,
      forms: [],
      discoveredAt: node.observedAt,
      intent: `Discovered ${node.elementCount} interactive elements`,
    }
  })

  // Convert DOM graph edges to AppWorkflowTransitions
  const transitions: AppWorkflowTransition[] = graph.edges.map((edge, index) => {
    // Find screen indices
    const fromIndex = graph.nodes.findIndex(n => n.id === edge.from)
    const toIndex = graph.nodes.findIndex(n => n.id === edge.to)
    
    if (fromIndex === -1 || toIndex === -1) {
      return null
    }

    const fromScreenId = `S${String(fromIndex + 1).padStart(3, '0')}`
    const toScreenId = `S${String(toIndex + 1).padStart(3, '0')}`

    return {
      id: `tr-${index + 1}`,
      fromScreenId,
      toScreenId,
      action: edge.action,
      actionType: edge.transition === 'navigation' ? 'navigation' as const : 'click' as const,
    }
  }).filter(Boolean) as AppWorkflowTransition[]

  // Build test steps from action ledger
  const steps: TestPlanStep[] = (job.actionLedger?.entries || [])
    .filter(entry => entry.status !== 'untested')
    .map((entry, index) => {
      // Find which screen this action belongs to
      const screenIndex = graph.nodes.findIndex(n => n.url === entry.screenUrl)
      const screenId = screenIndex >= 0 ? `S${String(screenIndex + 1).padStart(3, '0')}` : 'S001'
      const screen = screens.find(s => s.id === screenId)

      return {
        id: `step-${index + 1}`,
        screenId,
        screenName: screen?.name || entry.screenPath,
        stepIndex: index + 1,
        actionType: entry.type === 'input' ? 'fill' as const : 'click' as const,
        targetName: entry.name,
        selector: entry.selector,
        expectedResult: `Test ${entry.name}`,
        actualResult: entry.evidence?.observedOutcome,
        status: entry.status === 'passed' ? 'passed' as const :
               entry.status === 'failed' ? 'failed' as const :
               entry.status === 'blocked' ? 'blocked' as const : 'pending' as const,
        screenshotUrl: entry.evidence?.beforeScreenshotUrl || entry.evidence?.afterScreenshotUrl,
        evidenceTimestamp: entry.lastTestedAt || entry.discoveredAt,
      }
    })

  const testedCount = steps.filter(s => s.status === 'passed' || s.status === 'failed' || s.status === 'blocked').length

  return {
    id: `plan-dom-${job.id}`,
    targetUrl: job.targetUrl,
    screens,
    transitions,
    steps,
    requiredFileTypes: [],
    status: job.status === 'completed' ? 'completed' : job.status === 'running' ? 'testing' : 'planned',
    coverage: {
      screensTested: screens.length,
      totalScreens: screens.length,
      actionsTested: testedCount,
      totalActions: steps.length,
      formsTested: 0,
      totalForms: 0,
      percentage: steps.length > 0 ? Math.round((testedCount / steps.length) * 100) : 100,
    },
  }
}

/**
 * Synthesizes a structured FullAppTestPlan from any existing AutomationJob
 * (including chat runs with checklists, thinking models, and screenshots)
 * so the Full App tab is richly populated with nodes, edges, steps, and coverage.
 * 
 * Routes to appropriate synthesis based on available data:
 * 1. Existing fullAppTestPlan (already complete)
 * 2. DOM Discovery Graph (Full App Testing mode)
 * 3. Checklist/screens (chat/crawl mode)
 */
export function synthesizeFullAppPlanFromJob(job: AutomationJob | null): FullAppTestPlan | null {
  if (!job) return null

  // If the job already has a fully formed fullAppTestPlan, ensure all action screens are present
  if (job.fullAppTestPlan && job.fullAppTestPlan.screens && job.fullAppTestPlan.screens.length > 0) {
    return ensureEveryActionHasScreen(job.fullAppTestPlan)
  }

  // Try DOM Discovery Graph first (Full App Testing mode)
  if (job.domDiscoveryGraph && job.domDiscoveryGraph.nodes && job.domDiscoveryGraph.nodes.length > 0) {
    const domPlan = synthesizeFullAppPlanFromDomGraph(job)
    if (domPlan) {
      return domPlan
    }
  }

  // Fallback: synthesize from checklist/screens for chat/crawl modes

  // Look for checklist in either job.checklist or job.messages
  const checklist =
    (job.checklist && job.checklist.length > 0
      ? job.checklist
      : job.messages?.find((m) => m.checklist && m.checklist.length > 0)?.checklist) || []

  // Look for thinkingModel in either job.thinkingModel or job.messages
  const thinkingModel =
    job.thinkingModel ||
    job.messages?.find((m) => m.thinkingModel)?.thinkingModel

  const hasScreens = job.screens && job.screens.length > 0
  const hasHistory = job.actionHistory && job.actionHistory.length > 0

  if (checklist.length === 0 && !hasScreens && !thinkingModel && !hasHistory) {
    return null
  }

  // 1. Identify primary screenshot
  const primaryScreenshot =
    job.currentScreenshotUrl ||
    job.screens?.find((s) => s.screenshotUrl)?.screenshotUrl ||
    checklist.find((c) => c.screenshotUrl)?.screenshotUrl ||
    job.messages?.find((m) => m.imageUrl)?.imageUrl ||
    undefined

  // 2. Identify primary screen name & path
  let screenName = "Client Document Portal — Landlord Accounting"
  if (thinkingModel?.screenUnderstanding) {
    const raw = thinkingModel.screenUnderstanding.split(".")[0] || ""
    const clean = raw.replace(/^General Application Screen:\s*"?/i, "").replace(/"?$/, "").trim()
    if (clean) screenName = clean
  } else if (job.screens && job.screens[0]?.title) {
    screenName = job.screens[0].title.replace(/^Test\s*\d+:\s*/i, "")
  }

  const primaryUrl = job.targetUrl || "http://localhost:3001"
  const primaryPath = "/"

  // 3. Catalog actionable elements
  const elements: ActionableElement[] = []
  const seenElemNames = new Set<string>()

  if (thinkingModel?.identifiedElements) {
    for (const el of thinkingModel.identifiedElements) {
      const clean = el.name.trim()
      if (clean && !seenElemNames.has(clean.toLowerCase())) {
        seenElemNames.add(clean.toLowerCase())
        elements.push({
          id: `elem-${elements.length + 1}`,
          name: clean,
          type: (el.type as ActionableElementType) || "button",
          isInteractive: true,
          tested: false,
          testStatus: "pending",
        })
      }
    }
  }

  if (checklist.length > 0) {
    for (const chk of checklist) {
      const clean = chk.title
        .replace(/^Test\s*\d+:\s*/i, "")
        .replace(/\s*\(header\)|\s*\(sidebar\)/i, "")
        .trim()
      if (clean && !seenElemNames.has(clean.toLowerCase())) {
        seenElemNames.add(clean.toLowerCase())
        elements.push({
          id: `elem-${elements.length + 1}`,
          name: clean,
          type: /button|add/i.test(chk.title)
            ? "button"
            : /document|note|home|flat|house|test/i.test(chk.title)
            ? "link"
            : "button",
          isInteractive: true,
          tested: chk.status === "passed" || chk.status === "failed",
          testStatus: chk.status === "passed" ? "passed" : chk.status === "failed" ? "failed" : "pending",
        })
      }
    }
  }

  // 4. Construct Screen Nodes
  const screens: AppScreenNode[] = [
    {
      id: "S001",
      name: screenName,
      url: primaryUrl,
      path: primaryPath,
      screenshotUrl: primaryScreenshot,
      actionableElements: elements,
      forms: [],
      discoveredAt: job.startedAt || new Date().toISOString(),
    },
  ]

  // Track discovered distinct views / screens from job.screens and checklist
  const seenViews = new Set<string>([
    "home",
    "dashboard",
    "landlordaccountingclient portal",
    "client document portal — landlord accounting",
    screenName.toLowerCase(),
  ])

  if (job.screens && job.screens.length > 0) {
    for (const s of job.screens) {
      const cleanTitle = (s.title || "")
        .replace(/^Test\s*\d+:\s*/i, "")
        .replace(/\s*\(header\)|\s*\(sidebar\)/i, "")
        .trim()
      const key = cleanTitle.toLowerCase()
      const sPath = s.path && s.path !== "/" ? s.path : `/#${key.replace(/\s+/g, "-")}`

      if (cleanTitle && !seenViews.has(key)) {
        seenViews.add(key)
        const sId = `S${String(screens.length + 1).padStart(3, "0")}`
        screens.push({
          id: sId,
          name: cleanTitle,
          url: s.url || primaryUrl,
          path: sPath,
          screenshotUrl: s.screenshotUrl || primaryScreenshot,
          actionableElements: [
            {
              id: `${sId}-elem-1`,
              name: cleanTitle,
              type: /add/i.test(cleanTitle) ? "button" : "link",
              tested: false,
              testStatus: "pending",
              isInteractive: true,
            },
          ],
          forms: [],
          discoveredAt: s.testedAt || new Date().toISOString(),
        })
      }
    }
  }

  // 5. Construct transitions and steps so EVERY action has its own distinct screen
  const transitions: AppWorkflowTransition[] = []
  if (screens.length > 1) {
    for (let i = 1; i < screens.length; i++) {
      transitions.push({
        id: `tr-${i}`,
        fromScreenId: "S001",
        toScreenId: screens[i].id,
        action: `Click ${screens[i].name}`,
        actionType: /add/i.test(screens[i].name) ? "modal_open" : "navigation",
      })
    }
  }

  // 6. Construct structured test steps & dedicated action screens
  const steps: TestPlanStep[] = []
  if (checklist.length > 0) {
    checklist.forEach((chk, idx) => {
      const actionName = chk.title.replace(/^Test\s*\d+:\s*/i, "").trim()
      const sId = `S${String(screens.length + 1).padStart(3, "0")}`
      const screenTitle = actionName ? `${actionName} (Action Screen)` : `Action ${idx + 1}`
      const sPath = `/#action-${idx + 1}-${encodeURIComponent(actionName.toLowerCase().replace(/\s+/g, "-"))}`
      const screenShot = chk.screenshotUrl || primaryScreenshot

      screens.push({
        id: sId,
        name: screenTitle,
        url: primaryUrl,
        path: sPath,
        screenshotUrl: screenShot,
        actionableElements: [
          {
            id: `${sId}-elem-1`,
            name: actionName,
            type: /button|add|submit/i.test(chk.title) ? "button" : /input|fill/i.test(chk.title) ? "input" : "link",
            tested: chk.status === "passed" || chk.status === "failed",
            testStatus: chk.status === "passed" ? "passed" : chk.status === "failed" ? "failed" : "pending",
            isInteractive: true,
          },
        ],
        forms: [],
        discoveredAt: job.startedAt || new Date().toISOString(),
      })

      const isLogoutAction = /log\s*out|sign\s*out|log\s*off/i.test(actionName) || /log\s*out|sign\s*out|log\s*off/i.test(chk.title)

      transitions.push({
        id: `tr-${transitions.length + 1}`,
        fromScreenId: "S001",
        toScreenId: sId,
        action: `${chk.title.startsWith("Test") ? chk.title : `Click ${actionName}`}`,
        actionType: /modal|dialog/i.test(actionName) ? "modal_open" : "click",
      })

      if (isLogoutAction) {
        // Map logout step directly back to S001 Login to complete the workflow cycle
        transitions.push({
          id: `tr-logout-${transitions.length + 1}`,
          fromScreenId: sId,
          toScreenId: "S001",
          action: `Log out ➔ Login (Workflow Completed)`,
          actionType: "navigation",
        })
      } else {
        // Add verified backward return transition so map flow verifies bidirectional integrity
        transitions.push({
          id: `tr-return-${transitions.length + 1}`,
          fromScreenId: sId,
          toScreenId: "S001",
          action: `Return / Back ↩️ (Verified)`,
          actionType: /modal|dialog/i.test(actionName) ? "modal_close" : "navigation",
        })
      }

      steps.push({
        id: `step-${idx + 1}`,
        screenId: sId,
        screenName: screenTitle,
        stepIndex: idx + 1,
        actionType: /add/i.test(chk.title) ? "click" : /input|fill|enter/i.test(chk.title) ? "fill" : "click",
        targetName: actionName,
        expectedResult: chk.expectedOutcome || chk.goal || `Verify ${actionName} responds properly.`,
        actualResult:
          chk.observations ||
          (chk.status === "passed"
            ? "Verified view/modal response and stable return."
            : chk.error || "Action test completed."),
        status: chk.status === "passed" ? "passed" : chk.status === "failed" ? "failed" : "pending",
        screenshotUrl: screenShot,
        evidenceTimestamp: job.finishedAt || new Date().toISOString(),
      })
    })
  } else if (elements.length > 0) {
    elements.forEach((el, idx) => {
      steps.push({
        id: `step-${idx + 1}`,
        screenId: "S001",
        screenName,
        stepIndex: idx + 1,
        actionType: el.type === "input" ? "fill" : "click",
        targetName: el.name,
        expectedResult: `Interact with ${el.name} and verify state stability.`,
        actualResult: undefined,
        status: "pending",
        screenshotUrl: primaryScreenshot,
        evidenceTimestamp: job.finishedAt || new Date().toISOString(),
      })
    })
  }

  const passedCount = steps.filter((s) => s.status === "passed").length
  const failedCount = steps.filter((s) => s.status === "failed").length
  const blockedCount = steps.filter((s) => s.status === "blocked").length

  return {
    id: `plan-synth-${job.id}`,
    targetUrl: primaryUrl,
    screens,
    transitions,
    steps,
    requiredFileTypes: [],
    status: job.status === "completed" ? "completed" : job.status === "running" ? "testing" : "planned",
    coverage: {
      screensTested: screens.length,
      totalScreens: screens.length,
      actionsTested: passedCount + failedCount + blockedCount,
      totalActions: steps.length,
      formsTested: 0,
      totalForms: 0,
      percentage:
        steps.length > 0
          ? Math.round(((passedCount + failedCount + blockedCount) / steps.length) * 100)
          : 100,
    },
  }
}
